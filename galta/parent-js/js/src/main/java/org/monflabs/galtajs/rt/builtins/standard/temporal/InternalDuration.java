package org.monflabs.galtajs.rt.builtins.standard.temporal;

/**
 * An internal duration record: calendar date units plus an exact time
 * duration.
 */
public record InternalDuration(DateDuration date, TimeDuration time) {

	public static final InternalDuration ZERO = new InternalDuration(DateDuration.ZERO,TimeDuration.ZERO);

	public int sign() {
		int s = date.sign();
		return s!=0 ? s : time.sign();
	}
}
